export function validateWorld(): string[] {
  const errors: string[] = [];
  const ids = new Set<string>();
  for (const room of Object.values(ROOMS)) {
    for (const door of room.doors)
      if (!ROOMS[door.to]) errors.push(`${room.id}: missing ${door.to}`);
    for (const pickup of room.pickups) {
      if (ids.has(pickup.id)) errors.push(`Duplicate pickup ${pickup.id}`);
      ids.add(pickup.id);
    }
  }
  return errors;
}
