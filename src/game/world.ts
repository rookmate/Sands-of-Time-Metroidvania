import type { Room, Platform, Door, Pickup, EnemySpawn } from "./types";
const p = (x: number, y: number, w: number, h = 24): Platform => ({
  x,
  y,
  w,
  h,
  oneWay: h <= 30,
});
const d = (
  x: number,
  y: number,
  to: string,
  label: string,
  requires?: Door["requires"],
  hint?: string,
): Door => ({ x, y, to, label, requires, hint });
const item = (
  id: string,
  kind: Pickup["kind"],
  x: number,
  y: number,
  requires?: Pickup["requires"],
): Pickup => ({ id, kind, x, y, requires });
const guard = (
  x: number,
  y: number,
  min: number,
  max: number,
  kind: EnemySpawn["kind"] = "guard",
  tier = 0,
): EnemySpawn => ({ x, y, patrol: [min, max], kind, tier });

